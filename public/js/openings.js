export function lineSide(opening, line) {
  return line.side || opening.side;
}

export function findLine(lineId) {
  for (const o of OPENINGS) {
    for (const l of o.lines) {
      if (l.id === lineId) return { opening: o, line: l };
    }
  }
  return null;
}

export function allLines() {
  const out = [];
  for (const o of OPENINGS) for (const l of o.lines) out.push({ opening: o, line: l });
  return out;
}

