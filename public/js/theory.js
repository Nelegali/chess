// Превращает уже экранированный текст в HTML, где первое упоминание каждого термина — кнопка.
export function linkTerms(escapedText) {
  let out = escapedText;
  const used = new Set();
  for (const g of GLOSSARY) {
    if (used.has(g.id)) continue;
    const re = new RegExp(`(^|[^а-яёА-ЯЁa-zA-Z>"=-])(${g.re})`, 'iu');
    // не трогаем то, что уже стало кнопкой
    const parts = out.split(/(<button[^>]*>.*?<\/button>)/);
    let done = false;
    out = parts
      .map((part) => {
        if (done || part.startsWith('<button')) return part;
        return part.replace(re, (m, pre, word) => {
          done = true;
          return `${pre}<button type="button" class="term" data-term="${g.id}">${word}</button>`;
        });
      })
      .join('');
    if (done) used.add(g.id);
  }
  return out;
}

